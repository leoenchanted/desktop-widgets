const recordDataChannelFrames = () => {
  window.__canvasWireFrames = [];
  const original = RTCDataChannel.prototype.send;
  RTCDataChannel.prototype.send = function send(data) {
    const bytes = data instanceof ArrayBuffer ? new Uint8Array(data) : ArrayBuffer.isView(data) ? new Uint8Array(data.buffer) : null;
    window.__canvasWireFrames.push(bytes ? new TextDecoder().decode(bytes) : String(data));
    return original.call(this, data);
  };
  const originalSocketSend = WebSocket.prototype.send;
  WebSocket.prototype.send = function send(data) {
    window.__canvasWireFrames.push(String(data));
    return originalSocketSend.call(this, data);
  };
};
